"""Génère ShopEase/Data/SeedCatalog.cs à partir de catalog.py."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from catalog import CATEGORIES, PRODUCTS

def cs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

lines = ["// <auto-generated> Généré par tools/generate_seed.py — ne pas modifier à la main.</auto-generated>",
         "namespace ShopEase.Data;", "", "internal static class SeedCatalog", "{",
         "    public static readonly (string Name, string Description)[] Categories =", "    {"]
lines += [f"        ({cs(c[0])}, {cs(c[1])})," for c in CATEGORIES]
lines += ["    };", "",
          "    public static readonly (string Slug, string Name, string Category, decimal Price, int Stock, int Sales, double Rating, int DaysAgo, string Description)[] Products =",
          "    {"]
for p in PRODUCTS:
    slug, name, cat, _icon, price, stock, sales, rating, days, desc = p
    lines.append(f"        ({cs(slug)}, {cs(name)}, {cs(cat)}, {price}m, {stock}, {sales}, {rating}, {days}, {cs(desc)}),")
lines += ["    };", "}", ""]
out = os.path.join(os.path.dirname(__file__), "..", "ShopEase", "Data", "SeedCatalog.cs")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print("écrit", out)
